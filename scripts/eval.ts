// Writes docs/EVAL.md: planted-error catch rate, coverage bucket checks, and duplicate
// detection on the synthetic data. A proof of concept on public docs and a fictional
// customer, not a benchmark.
import { writeFileSync } from 'node:fs'
import { buildPlan } from '../src/server/plan.js'
import { runData } from '../src/server/data.js'
import { loadConfig, loadCustomer, readJson } from '../src/server/store.js'
import { matchTool } from '../src/core/coverage.js'
import { scoreAgainstTruth } from '../src/core/data.js'
import type { Draft } from '../src/core/types.js'
import { PLANTED, caughtBy, plant } from '../tests/planted.js'

const customer = loadCustomer('halden')
const savedFile = readJson<{ draft: Draft; model: string; created_at: string }>('fixtures/drafts/halden.json')
const saved = savedFile.draft

const base = await buildPlan({ customer, draftOverride: saved })
const rows: string[] = []
let caught = 0
for (const e of PLANTED) {
  const p = await buildPlan({ customer, draftOverride: plant(saved, e) })
  const name = `${e.row.section}/${e.row.tool}/${e.row.item}`
  const held = p.verification.held.some((x) => x.row === name)
  const why = held ? caughtBy(p, e) : null
  if (why) caught++
  rows.push(`| ${e.description} | \`${e.bad}\` | ${why ? 'Caught' : '**MISSED**'} | ${why ? why.replace(/\|/g, '/').slice(0, 160) : ''} |`)
}

const cfg = loadConfig()
const cases: [string, string][] = [
  ['Okta', 'out_of_box'], ['Tenable VM', 'out_of_box'], ['CrowdStrike Falcon', 'out_of_box'], ['ServiceNow ITSM', 'out_of_box'],
  ['Microsoft Defender', 'confirm_with_safe'], ['ServiceNow', 'confirm_with_safe'], ['Tenable', 'confirm_with_safe'], ['Crowdstrike', 'confirm_with_safe'],
  ['Snyk', 'custom_work'], ['Acme Vuln Scanner', 'custom_work'], ['Microsoft Sentinel', 'custom_work'],
]
const covRows = cases.map(([t, want]) => {
  const r = matchTool(t, cfg)
  return { ok: r.bucket === want, line: `| ${t} | ${want} | ${r.bucket} | ${r.bucket === want ? 'Pass' : '**FAIL**'} |` }
})

const data = runData({ customer })
const score = scoreAgainstTruth(data, readJson<any>('data/halden/truth.json').record_entity)
const v = base.verification

const md = `# Evaluation (proof of concept)

Generated by \`npm run eval\`. Public vendor docs, a **fictional** customer, and **synthetic** data that I designed, with problems planted on purpose. These numbers show the checks work on the cases I thought of. They are not a benchmark of real-world accuracy.

## 1. Verifier: planted errors in the model draft

Baseline: the saved model draft (${savedFile.model}, ${savedFile.created_at.slice(0, 10)}) has ${v.facts_total} cited facts. ${v.facts_verified}/${v.facts_total} verify (${v.facts_corrected} with a corrected line number), and ${v.rows_held_back} of ${v.rows_total} rows are held back${v.held.length ? ':' : '.'}
${v.held.map((h) => `- \`${h.row}\`: ${h.reason}. Draft text: "${h.draft_text}"`).join('\n')}
${v.held.length ? '\nThis hold was not planted. Here the content was right, but the model tagged a header name as a version, so the citation was malformed and the verifier held the row back. Being strict costs one Confirm here, and it never shows a malformed fact.\n' : ''}

Each planted error is added to that draft on its own and the plan is rebuilt. To count as caught, the planted fact itself must fail verification (or the planted token must be named in the hold reason), the row must be held back (shown as Confirm), and the bad value must appear nowhere in the output.

**${caught}/${PLANTED.length} planted errors caught.**

| Planted error | Bad value | Result | Verifier's reason |
|---|---|---|---|
${rows.join('\n')}

What this does not cover: claims written as plain English words with no code-like token or number (for example "two regions") are not detected by the token check. They rely on the prompt rule and on human review of the draft.

## 2. Coverage check (code, not model)

**${covRows.filter((r) => r.ok).length}/${covRows.length} cases in the expected bucket.** Unit tests also check that every one of the ${cfg.integrations.integrations.length} cards matches itself and that tools absent from the list always land in Custom work.

| Customer says | Expected | Got | |
|---|---|---|---|
${covRows.map((r) => r.line).join('\n')}

## 3. Duplicate detection on synthetic data

${data.totals.asset_records} asset records from 3 tools, which are ${new Set(Object.values(readJson<any>('data/halden/truth.json').record_entity)).size} real machines in the truth file.

| Measure | Value |
|---|---|
| Same-machine record pairs in the truth file | ${score.true_same_machine_pairs} |
| Pairs merged automatically | ${score.merged_pairs} |
| Correct automatic merges | ${score.correct_merges} |
| **Wrong automatic merges** | **${score.wrong_merges}** |
| Same-machine pairs not merged | ${score.missed_pairs} (all ${score.missed_pairs_sent_to_review} sent to the review queue) |
| Review queue items | ${score.review_items} (${score.review_items_truly_same} truly the same machine, ${score.review_items_truly_different} truly different) |

The design choice: weak evidence (same hostname only, shared IP only, a device name equal to a hostname) never merges on its own. It goes to a person. That trades some manual review for zero silent wrong merges, which matters because a wrong merge hides a machine from the risk figure.

Data checks on this data set: ${data.checks.map((c) => `${c.check}: ${c.level}`).join(', ')}. Ready to feed a risk number: ${data.ready ? 'yes' : 'no'}.
`
writeFileSync('docs/EVAL.md', md)
console.log(`planted errors caught: ${caught}/${PLANTED.length}; coverage ${covRows.filter((r) => r.ok).length}/${covRows.length}; wrong merges ${score.wrong_merges}`)
